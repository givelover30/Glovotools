/**
 * Explicit alias lookup table mapping legacy switch cases (`pdf-crop`, `pdf-unlock`,
 * `pdf-rotate`, `pdf-watermark`, `pdf-protect`, `ocr-pdf`) to their canonical IDs.
 */
export const PDF_TOOL_ALIAS_MAP: Readonly<Record<string, string>> = (() => {
  const map: Record<string, string> = {};
  for (const cap of Object.values(PDF_TOOL_OPERATION_REGISTRY)) {
    map[cap.canonicalId] = cap.canonicalId;
    for (const alias of cap.aliases) {
      map[alias] = cap.canonicalId;
    }
  }
  return map;
})();

