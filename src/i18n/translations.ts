export function getLocalizedCategory(cat: any, language: string) {
  if (!cat) return cat;
  const langDict = TRANSLATIONS[language as Language] || TRANSLATIONS.en;
  const titleKey = 'cat.' + cat.id;
  const descKey = 'cat.desc.' + cat.id;
  const translatedTitle = langDict[titleKey] || TRANSLATIONS.en[titleKey] || cat.title || cat.name;
  const translatedDesc = langDict[descKey] || TRANSLATIONS.en[descKey] || cat.description;
  return {
    ...cat,
    title: translatedTitle,
    name: translatedTitle,
    description: translatedDesc,
  };
}

export function getLocalizedSubcategory(subcat: any, language: string) {
  if (!subcat) return subcat;
  if (typeof subcat === 'string') {
    const subId = subcat.toLowerCase().replace(/[^a-z0-9]+/g, '-');
    const subKey = 'subcat.' + subId;
    const langDict = TRANSLATIONS[language as Language] || TRANSLATIONS.en;
    return langDict[subKey] || TRANSLATIONS.en[subKey] || subcat;
  }
  const subKey = 'subcat.' + subcat.id;
  const langDict = TRANSLATIONS[language as Language] || TRANSLATIONS.en;
  const translatedName = langDict[subKey] || TRANSLATIONS.en[subKey] || subcat.name;
  return {
    ...subcat,
    name: translatedName,
  };
}
