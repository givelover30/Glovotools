export const EXPLICIT_CONTRACT_IDS = new Set<string>([
  ...ALL_REGISTERED_CONTRACTS.map((c) => c.id),
  'cloud-storage-cost-optimizer'
]);

export function getToolStatusInfo(tool: Pick<CalculatorMeta, 'id' | 'category'>): ToolStatusInfo {
  const hasCustomUi = CUSTOM_UI_TOOL_IDS.has(tool.id);
  const isStaticGuide = STATIC_GUIDE_TOOL_IDS.has(tool.id);
  const isWorkspace = !hasCustomUi && WORKSPACE_CATEGORIES.has(tool.category);
  const hasExplicitContract = EXPLICIT_CONTRACT_IDS.has(tool.id);
  const hasPassingTestEvidence = TESTED_PASSING_TOOL_IDS.has(tool.id);

  if (isStaticGuide) {
    return {
      id: tool.id,
      tier: 'static-guide',
      hasCustomUi,
      hasExplicitContract,
      hasPassingTestEvidence: false,
      isSyntheticFallback: false,
      isStaticGuide: true,
      isWorkspace: false,
      labelEn: 'Reference guide',
      labelEs: 'Guía de referencia',
      evidenceSource: 'Static *ReferenceCalculator component'
    };
  }

  if (isWorkspace) {
    return {
      id: tool.id,
      tier: 'workspace',
      hasCustomUi: false,
      hasExplicitContract,
      hasPassingTestEvidence: false,
      isSyntheticFallback: false,
      isStaticGuide: false,
      isWorkspace: true,
      labelEn: 'Interactive workspace',
      labelEs: 'Espacio interactivo',
      evidenceSource: `Dedicated category workspace (${tool.category})`
    };
  }

  if (hasCustomUi || hasExplicitContract) {
    if (hasPassingTestEvidence) {
      return {
        id: tool.id,
        tier: 'explicit-tested',
        hasCustomUi,
        hasExplicitContract,
        hasPassingTestEvidence: true,
        isSyntheticFallback: false,
        isStaticGuide: false,
        isWorkspace: false,
        labelEn: 'Tested formula',
        labelEs: 'Fórmula probada',
        evidenceSource: hasExplicitContract
          ? 'Explicit formula with passing AuditRunner/EngineTestSuite verification'
          : 'Custom UI component with passing verification fixture'
      };
    }

    return {
      id: tool.id,
      tier: 'explicit-untested',
      hasCustomUi,
      hasExplicitContract,
      hasPassingTestEvidence: false,
      isSyntheticFallback: false,
      isStaticGuide: false,
      isWorkspace: false,
      labelEn: 'Dedicated tool',
      labelEs: 'Herramienta dedicada',
      evidenceSource: hasCustomUi
        ? 'Dedicated React UI component without independent oracle pass'
        : 'Explicit CalculationContract without independent oracle pass'
    };
  }

  return {
    id: tool.id,
    tier: 'generic-fallback',
    hasCustomUi: false,
    hasExplicitContract: false,
    hasPassingTestEvidence: false,
    isSyntheticFallback: true,
    isStaticGuide: false,
    isWorkspace: false,
    labelEn: 'Formula preview (generic estimate)',
    labelEs: 'Vista previa (estimación genérica)',
    evidenceSource: 'Generic fallback generateSmartFields contract'
  };
}
